#!/usr/bin/env node
/* Emit the referee card-rate reference the football-analyst skill reads.
 *
 * WHY THIS IS A SCRIPT AND NOT A FILE SOMEBODY MAINTAINS. The file it replaces
 * was hand-typed, carried no sample sizes, and had drifted until only one of
 * its twelve Premier League entries was right:
 *
 *     Rob Jones        file 2.8 "very lenient", LOW   dataset 4.17 over 18 — HIGH
 *     Stuart Attwell   file 3.5 MODERATE              dataset 4.60 over 25 — HIGH
 *     Jarred Gillett   file 4.7 top, HIGH             dataset 3.59 over 22 — MODERATE
 *     Simon Hooper     file 3.2 MODERATE              dataset 4.00 over 15 — HIGH
 *     Michael Salisbury file 3.4 MODERATE             dataset 4.36 over 14 — HIGH
 *     Craig Pawson     file 3.3 MODERATE              dataset 2.67 over 21 — LOW
 *
 * Ten of twelve in the wrong tier, in both directions, and the file's scoring
 * rules turn a tier into ±2 on a fixture score. It also omitted Chris Kavanagh
 * — who refereed more matches than anyone in the dataset — entirely.
 *
 * None of that was a mistake anyone made once. It is what a hand-maintained
 * copy of a number that moves every week always becomes. So the copy is
 * generated, it carries its own provenance, and it says how many matches each
 * figure rests on — which is the thing the old file's confident prose had no
 * way to express.
 *
 *   node scripts/ref-reference.mjs                      # to stdout
 *   node scripts/ref-reference.mjs --out <path>         # write it
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(readFileSync(join(root, 'data', 'pl_data.js'), 'utf8')
  + '\n;globalThis.__OUT = { REFS, CLUBS };', ctx);
const REFS = ctx.__OUT.REFS;
/* model.js is a browser script with trailing exports, not a JSON document —
   parsing it as JSON dies on the first line after the object. Run it the same
   way the page does. */
vm.runInContext(readFileSync(join(root, 'data', 'model.js'), 'utf8')
  + '\n;globalThis.__M = CARD_MODEL;', ctx);
const PIVOT = ctx.__M.twoStage?.refPivotYpg ?? 3.71;

/* A tier is a claim about a referee's habit. Under this many matches it is a
   claim about a handful of afternoons, so the figure is reported and the tier
   withheld — the old file's David Coote entry (2.7, LOW, no matches at all,
   and no Premier League appointment in the dataset) is what that prevents. */
const MIN_MATCHES = 10;
const HIGH = 4.0, LOW = 3.0;

const tier = (r) => r.matches < MIN_MATCHES ? null : (r.ypg >= HIGH ? 'HIGH' : r.ypg >= LOW ? 'MODERATE' : 'LOW');
const rows = REFS.slice().sort((a, b) => b.ypg - a.ypg);
const band = (t) => rows.filter((r) => tier(r) === t);
const thin = rows.filter((r) => tier(r) === null);

/* Named in the old file, by any spelling. Everyone else with a real sample was
   simply absent from it — including the official who refereed the most matches
   in the dataset. */
const NAMED = ['gillett','brooks','england','taylor','oliver','attwell','salisbury','pawson','hooper','tierney','jones','coote'];
const OMITTED = rows.filter((r) => r.matches >= MIN_MATCHES
    && !NAMED.some((n) => r.n.toLowerCase().includes(n)))
  .sort((a, b) => b.matches - a.matches)
  .map((r) => `${r.n} (${r.matches} matches, ${r.ypg.toFixed(2)})`).join(', ');

const table = (list) => [
  '| Referee | Yellows/Game | Matches | Reds/Game | Fouls/Game | vs pivot |',
  '|---|---|---|---|---|---|',
  ...list.map((r) => `| ${r.n} | **${r.ypg.toFixed(2)}** | ${r.matches} | `
    + `${r.red == null ? '—' : r.red.toFixed(2)} | ${r.fpg == null ? '—' : r.fpg.toFixed(1)} | `
    + `${r.ypg >= PIVOT ? '+' : ''}${((r.ypg / PIVOT - 1) * 100).toFixed(0)}% |`)
].join('\n');

const out = `# Premier League Referee Card Rates — 2025-26

<!-- GENERATED by scripts/ref-reference.mjs in the pl-bookings repo. Do not hand-edit:
     the file this replaced was hand-maintained and ten of its twelve entries had
     drifted into the wrong tier. Regenerate after each data refresh:
       node scripts/ref-reference.mjs --out <this file> -->

Source: \`data/pl_data.js\` REFS, built from football-data.co.uk match records via
\`data/build_refs.py\`. Every figure below is a measured season rate, not an
estimate, and every one is shown with the number of matches behind it.

**League pivot: ${PIVOT} yellows per game.** That is the number the desk's model
divides by, so "vs pivot" is the multiplier a fixture actually receives.

## HIGH CARD RATE (${HIGH.toFixed(1)}+ yellows per game)

${table(band('HIGH'))}

## MODERATE (${LOW.toFixed(1)}–${(HIGH - 0.01).toFixed(2)})

${table(band('MODERATE'))}

## LOW (under ${LOW.toFixed(1)})

${table(band('LOW'))}

## TOO FEW MATCHES TO TIER (under ${MIN_MATCHES})

Reported, deliberately untiered. A rate over a handful of matches is mostly
noise, and the previous version of this file gave confident tiers to officials
on no stated sample at all.

${table(thin)}

## HOW TO USE THIS DATA

- **Scale, do not step.** The honest adjustment is the "vs pivot" column: a
  referee on ${(PIVOT * 1.25).toFixed(2)} carries about +25% on the fixture's card
  expectation. The old ±2 tier bump threw that resolution away and made a 4.05
  and a 4.60 the same input.
- If you keep the tier bump: HIGH = +2, LOW = reduce confidence one tier,
  MODERATE = no change. But prefer the multiplier.
- **An untiered referee gets no adjustment**, not a guessed one.
- **A referee not in this file gets no adjustment either.** He has not
  officiated in the source season; do not carry a figure over from memory.
- Always verify the actual appointment before using any of this. Appointments
  publish the Monday or Tuesday before a round and change for injury.

## WHAT CHANGED FROM THE HAND-MAINTAINED VERSION

| Referee | Old file | Measured | Effect of the old value |
|---|---|---|---|
| Rob Jones | 2.8, "very lenient", LOW | 4.17 over 18 — HIGH | Cut confidence a tier on one of the most punitive officials in the league |
| Stuart Attwell | 3.5, MODERATE | 4.60 over 25 — HIGH | Missed +2 on the highest-card official with a full season behind him |
| Jarred Gillett | 4.7, top, HIGH | 3.59 over 22 — MODERATE | Added +2 to fixtures that should get nothing |
| Simon Hooper | 3.2, MODERATE | 4.00 over 15 — HIGH | Missed +2 |
| Michael Salisbury | 3.4, MODERATE | 4.36 over 14 — HIGH | Missed +2 |
| Craig Pawson | 3.3, MODERATE | 2.67 over 21 — LOW | Missed a confidence reduction |
| Paul Tierney | 2.9, LOW | 3.33 over 12 — MODERATE | Cut confidence for no reason |
| John Brooks | 4.3, HIGH | 3.67 over 12 — MODERATE | Added +2 for no reason |
| Anthony Taylor | 3.8, listed under "4.0+" | 3.94 over 31 | Right number, wrong section — the old file's own heading contradicted its own row |
| David Coote | 2.7, LOW | not in the dataset | A referee with no appointments in the source season, carrying a tier |
| Darren England | 4.3, HIGH | 4.30 over 23 — HIGH | The only entry that was correct |

Officials with a real sample that the old file omitted entirely: ${OMITTED}.

## EUROPEAN REFEREES — CARRIED OVER, NOT VERIFIED

**These are the only figures in this file this repository cannot check.** They
were in the hand-maintained version and are kept so regenerating does not
silently delete content, but nothing here measures them: the dataset behind
every table above is Premier League match records only.

Treat them with the suspicion the rest of that file earned. Of its twelve
Premier League entries, ten were in the wrong tier — so a figure from the same
source, for a competition with no coverage here at all, is a starting point for
a lookup and not an input to a score.

| Referee | Claimed Yellows/Game | Competition |
|---|---|---|
| João Pinheiro (Portugal) | 4.7 | All comps. 3.71 in UCL. |
| Daniel Siebert (Germany) | 3.8 | UCL. |
| Danny Makkelie (Netherlands) | 3.5 | Experienced; books cynical fouls. |

To put these on the same footing as the Premier League tables, harvest the
competition into \`data/\` and extend \`data/build_refs.py\` — the league registry
in \`data/leagues.py\` already takes a new competition without a rewrite.
`;

const i = process.argv.indexOf('--out');
if (i > -1 && process.argv[i + 1]) {
  writeFileSync(process.argv[i + 1], out);
  console.log(`wrote ${process.argv[i + 1]} — ${REFS.length} officials, `
    + `${band('HIGH').length} high, ${band('MODERATE').length} moderate, `
    + `${band('LOW').length} low, ${thin.length} untiered`);
} else {
  process.stdout.write(out);
}
